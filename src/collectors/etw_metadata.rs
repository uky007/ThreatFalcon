//! Public ETW extended-data contracts, independent of TDH payload schemas.
//! Publisher identity is NOT the identity of a process named in the payload.
use crate::events::{EventSource, ThreatEvent};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct CaptureOptions {
    pub process_start_key: bool,
    pub event_key: bool,
    pub stack_trace: bool,
}

impl CaptureOptions {
    pub fn enabled(self) -> bool {
        self.process_start_key || self.event_key || self.stack_trace
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExtendedMetadata {
    /// Fresh for each collector start, deliberately NOT an OS boot identifier.
    /// Prevents accidental joins across boots or restarts without a trusted boot ID.
    pub capture_id: Uuid,
    pub header_pid: u32,
    pub header_tid: u32,
    pub requested: CaptureOptions,
    pub process_start_key: Option<u64>,
    pub event_key: Option<u64>,
    pub stacks: Vec<StackTrace>,
    /// Types only: never retain arbitrary extension values (e.g. SID).
    pub omitted_types: Vec<u16>,
    pub issues: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StackTrace {
    pub pointer_width: u8,
    pub match_id: u64,
    /// Native addresses, in native order. No memory reads or symbol lookups.
    pub addresses: Vec<u64>,
    pub original_frame_count: u16,
    pub locally_truncated: bool,
    /// Reaching the documented ETW limit is not proof of upstream truncation.
    pub capture_limit_reached: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct PublisherIdentity {
    pub agent_id: Uuid,
    pub capture_id: Uuid,
    pub process_start_key: u64,
    pub pid: u32,
}

/// Cumulative callback/queue counters for this collector run, not disk receipts
/// and not a count of all events generated by the provider.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct ProviderTelemetry {
    pub capture_id: Option<Uuid>,
    pub requested: CaptureOptions,
    pub observed: u64,
    pub normalized: u64,
    pub queue_admitted: u64,
    pub queue_dropped: u64,
    pub extended_events: u64,
    pub publisher_identity_events: u64,
    pub stack_events: u64,
    pub metadata_issue_events: u64,
    pub last_observed_at: Option<chrono::DateTime<chrono::Utc>>,
}

/// Do not promote a publisher key into ProcessContext / payload actor identity.
pub fn publisher_identity(event: &ThreatEvent) -> Option<PublisherIdentity> {
    if !matches!(event.source, EventSource::Etw { .. }) || event.agent_id.is_nil() {
        return None;
    }
    let provenance = event.provenance.as_ref()?;
    if Uuid::parse_str(&provenance.provider_guid)
        .ok()
        .is_none_or(|guid| guid.is_nil())
    {
        return None;
    }
    let metadata = provenance.etw_extended.as_ref()?;
    if metadata.capture_id.is_nil()
        || !metadata.requested.process_start_key
        || !provenance.original_time
        || metadata.header_pid == 0
        || metadata.header_pid == u32::MAX
        || metadata
            .issues
            .iter()
            .any(|s| s.starts_with("extended_") || s.starts_with("process_start_key_"))
    {
        return None;
    }
    Some(PublisherIdentity {
        agent_id: event.agent_id,
        capture_id: metadata.capture_id,
        process_start_key: metadata.process_start_key.filter(|key| *key != 0)?,
        pid: metadata.header_pid,
    })
}

/// New opt-in native records must never enter legacy PID-only actor joins.
pub fn has_extended_metadata(event: &ThreatEvent) -> bool {
    matches!(event.source, EventSource::Etw { .. })
        && event
            .provenance
            .as_ref()
            .is_some_and(|p| p.etw_extended.is_some())
}

pub fn requires_explicit_identity(event: &ThreatEvent) -> bool {
    has_extended_metadata(event) || super::etw_normalize::is_powershell_script(event)
}

// Documented evntcons.h values, checked against the SDK in Windows tests.
pub const STACK32: u16 = 5;
pub const STACK64: u16 = 6;
pub const EVENT_KEY: u16 = 10;
pub const PROCESS_START_KEY: u16 = 13;
pub const MAX_ITEMS: usize = 32;
pub const MAX_STACKS: usize = 4;
pub const MAX_FRAMES: usize = 128;
pub const ETW_FRAME_LIMIT: usize = 192;
pub const MAX_ITEM_BYTES: usize = 8 + ETW_FRAME_LIMIT * 8;

#[allow(dead_code)] // Native callers are Windows-only; tests are portable.
pub struct Builder {
    metadata: ExtendedMetadata,
    items: usize,
    process_key_seen: bool,
    event_key_seen: bool,
}

#[allow(dead_code)]
impl Builder {
    pub fn new(
        capture_id: Uuid,
        header_pid: u32,
        header_tid: u32,
        requested: CaptureOptions,
    ) -> Self {
        Self {
            metadata: ExtendedMetadata {
                capture_id,
                header_pid,
                header_tid,
                requested,
                process_start_key: None,
                event_key: None,
                stacks: Vec::new(),
                omitted_types: Vec::new(),
                issues: Vec::new(),
            },
            items: 0,
            process_key_seen: false,
            event_key_seen: false,
        }
    }

    pub fn issue(&mut self, code: &str) {
        if !self.metadata.issues.iter().any(|s| s == code) {
            self.metadata.issues.push(code.into());
        }
    }

    pub fn wanted(&self, kind: u16) -> bool {
        match kind {
            PROCESS_START_KEY => self.metadata.requested.process_start_key,
            EVENT_KEY => self.metadata.requested.event_key,
            STACK32 | STACK64 => self.metadata.requested.stack_trace,
            _ => false,
        }
    }

    /// None means a wanted native item could not safely be read. Duplicate keys
    /// invalidate that key, even if the duplicate has identical bytes.
    pub fn push(&mut self, kind: u16, bytes: Option<&[u8]>) {
        self.items = self.items.saturating_add(1);
        if self.items > MAX_ITEMS {
            self.issue("extended_item_count_limit");
            return;
        }
        if !self.wanted(kind) {
            if !self.metadata.omitted_types.contains(&kind) {
                self.metadata.omitted_types.push(kind);
            }
            return;
        }
        match kind {
            PROCESS_START_KEY | EVENT_KEY => {
                let process = kind == PROCESS_START_KEY;
                let duplicate = if process {
                    std::mem::replace(&mut self.process_key_seen, true)
                } else {
                    std::mem::replace(&mut self.event_key_seen, true)
                };
                let parsed = bytes
                    .filter(|b| b.len() == 8)
                    .map(|b| u64::from_le_bytes(b.try_into().unwrap()));
                if process {
                    self.metadata.process_start_key = if duplicate { None } else { parsed };
                } else {
                    self.metadata.event_key = if duplicate { None } else { parsed };
                }
                if duplicate {
                    self.issue(if process {
                        "process_start_key_duplicate"
                    } else {
                        "event_key_duplicate"
                    });
                } else if parsed.is_none() {
                    self.issue(if process {
                        "process_start_key_invalid_size"
                    } else {
                        "event_key_invalid_size"
                    });
                } else if process && parsed == Some(0) {
                    self.issue("process_start_key_zero");
                }
            }
            STACK32 | STACK64 => {
                if self.metadata.stacks.len() >= MAX_STACKS {
                    self.issue("stack_count_limit");
                    return;
                }
                let width = if kind == STACK32 { 4 } else { 8 };
                let Some(bytes) = bytes.filter(|b| {
                    b.len() >= 8 + width && b.len() <= MAX_ITEM_BYTES && (b.len() - 8) % width == 0
                }) else {
                    self.issue("stack_invalid_size");
                    return;
                };
                let count = (bytes.len() - 8) / width;
                if count > ETW_FRAME_LIMIT {
                    self.issue("stack_frame_count_invalid");
                    return;
                }
                let addresses = bytes[8..]
                    .chunks_exact(width)
                    .take(MAX_FRAMES)
                    .map(|b| {
                        if width == 4 {
                            u32::from_le_bytes(b.try_into().unwrap()) as u64
                        } else {
                            u64::from_le_bytes(b.try_into().unwrap())
                        }
                    })
                    .collect();
                self.metadata.stacks.push(StackTrace {
                    pointer_width: width as u8,
                    match_id: u64::from_le_bytes(bytes[..8].try_into().unwrap()),
                    addresses,
                    original_frame_count: count as u16,
                    locally_truncated: count > MAX_FRAMES,
                    capture_limit_reached: count == ETW_FRAME_LIMIT,
                });
                if count > MAX_FRAMES {
                    self.issue("stack_locally_truncated");
                }
                if count == ETW_FRAME_LIMIT {
                    self.issue("stack_capture_limit_reached");
                }
            }
            _ => unreachable!(),
        }
    }

    pub fn finish(mut self) -> ExtendedMetadata {
        if self.metadata.requested.process_start_key && self.metadata.process_start_key.is_none() {
            self.issue("process_start_key_unavailable");
        }
        if self.metadata.requested.event_key && self.metadata.event_key.is_none() {
            self.issue("event_key_unavailable");
        }
        if self.metadata.requested.stack_trace && self.metadata.stacks.is_empty() {
            self.issue("stack_unavailable");
        }
        self.metadata
    }
}

